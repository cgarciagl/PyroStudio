import { invoke } from "@tauri-apps/api/core";
import type { MaskingProfile, MaskingRequest } from "../types/database";
import { useWorkspaceStore } from "../stores/workspaceStore";
import { dbService } from "./tauriDb";
import { toWorkspaceError } from "./workspaceService";
import { effectiveRules } from "../utils/maskingInference";

/**
 * Reusable data-masking profiles (Roadmap V3 · Fase 3).
 * - Folder workspace: `.pyro/masking/<id>.json`, hash-guarded writes.
 * - Local mode: localStorage on this computer.
 * Profiles hold rules only; a stable seed lives encrypted in the Vault.
 */
interface ProfileEntry {
  profile: MaskingProfile;
  contentHash: string;
}

const LOCAL_KEY = "pyro_masking_profiles_v1";
const hashes = new Map<string, string>();

const inWorkspace = () => useWorkspaceStore.getState().isFolderMode();

function readLocal(): MaskingProfile[] {
  try {
    const raw = localStorage.getItem(LOCAL_KEY);
    return raw ? (JSON.parse(raw) as MaskingProfile[]) : [];
  } catch {
    return [];
  }
}

function writeLocal(profiles: MaskingProfile[]) {
  localStorage.setItem(LOCAL_KEY, JSON.stringify(profiles));
}

export function newMaskingProfileId(): string {
  return `msk-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
}

/** Vault entry of a profile's stable seed (generated by Rust on first export). */
export const seedCredentialId = (profileId: string) => `masking-seed-${profileId}`;

/** Masking options for an export from a profile (or ad-hoc rules). */
export function toMaskingRequest(profile: Pick<MaskingProfile, "id" | "name" | "stableSeed" | "rules">): MaskingRequest {
  return {
    profileName: profile.name.trim() || undefined,
    rules: effectiveRules(profile.rules),
    seedCredentialId: profile.stableSeed && profile.id ? seedCredentialId(profile.id) : undefined,
  };
}

export const maskingProfiles = {
  async list(): Promise<MaskingProfile[]> {
    if (!inWorkspace()) {
      return readLocal().sort((a, b) => a.name.localeCompare(b.name));
    }
    try {
      const entries = await invoke<ProfileEntry[]>("workspace_list_masking_profiles");
      hashes.clear();
      for (const e of entries) hashes.set(e.profile.id, e.contentHash);
      return entries.map((e) => e.profile);
    } catch (e) {
      throw toWorkspaceError(e);
    }
  },

  async save(profile: MaskingProfile): Promise<MaskingProfile> {
    const clean: MaskingProfile = { ...profile, name: profile.name.trim(), rules: effectiveRules(profile.rules) };
    if (!inWorkspace()) {
      const list = readLocal().filter((p) => p.id !== clean.id);
      writeLocal([...list, clean]);
      return clean;
    }
    try {
      const entry = await invoke<ProfileEntry>("workspace_save_masking_profile", {
        profile: clean,
        expectedHash: hashes.get(clean.id) ?? "",
      });
      hashes.set(entry.profile.id, entry.contentHash);
      return entry.profile;
    } catch (e) {
      throw toWorkspaceError(e);
    }
  },

  async remove(id: string): Promise<void> {
    if (!inWorkspace()) {
      writeLocal(readLocal().filter((p) => p.id !== id));
    } else {
      try {
        await invoke("workspace_delete_masking_profile", { id });
        hashes.delete(id);
      } catch (e) {
        throw toWorkspaceError(e);
      }
    }
    // The stable seed (if any) is useless without its profile.
    await dbService.deleteCredential(seedCredentialId(id)).catch(() => {});
  },
};
